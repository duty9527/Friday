const WECHAT_TYPING_KEEPALIVE_MS = 5_000;
const WECHAT_TYPING_TICKET_TTL_MS = 15 * 60_000;
const WECHAT_QR_SESSION_TTL_MS = 10 * 60_000;

interface InternalWechatQrSession extends WechatQrLoginSession {
  apiBase: string;
  createdAt: number;
  inFlightPromise?: Promise<void>;
}

interface WechatTypingTicketEntry {
  ticket: string;
  botToken: string;
  expiresAt: number;
}

interface WechatTypingSession {
  channelId: string;
  userId: string;
  contextToken?: string;
  activeRefs: Set<string>;
  timer?: ReturnType<typeof setTimeout>;
  chain: Promise<void>;
  remoteTyping: boolean;
}

export interface WechatIlinkHostHooks {
  saveWechatChannel(input: {
    id?: string;
    platform: 'wechat';
    name: string;
    apiBase?: string;
    notifyAll?: boolean;
    allowedSenders?: string[];
  }): ImChannelView;
  syncPollers(): void;
  isRunning(): boolean;
}

/** Construct signed request headers expected by the Tencent WeChat iLink Bot API. */
export function buildWechatIlinkHeaders(botToken: string): Record<string, string> {
  const uin = randomBytes(4).readUInt32BE(0);
  return {
    'content-type': 'application/json',
    AuthorizationType: 'ilink_bot_token',
    Authorization: `Bearer ${botToken}`,
    'X-WECHAT-UIN': Buffer.from(String(uin), 'utf8').toString('base64'),
    'iLink-App-ClientVersion': '1',
  };
}

/** Parse a WeChat iLink `msgs[]` / webhook payload into a normalized inbound message. */
export function parseWechatIlinkMessage(
  channelId: string,
  raw: Record<string, unknown>,
  botAccountId?: string,
): ImInboundMessage | undefined {
  const msg = (raw.msg && typeof raw.msg === 'object' ? raw.msg : raw) as Record<string, unknown>;
  // Ignore outbound messages generated by the bot itself (message_type === 2)
  if (Number(msg.message_type) === 2) return undefined;
  const fromUserId = typeof msg.from_user_id === 'string' ? msg.from_user_id.trim() : '';
  if (!fromUserId) return undefined;
  if (botAccountId && fromUserId === botAccountId) return undefined;

  const itemList = Array.isArray(msg.item_list) ? msg.item_list as Array<Record<string, unknown>> : [];
  const textParts: string[] = [];
  for (const item of itemList) {
    const textItem = item.text_item as Record<string, unknown> | undefined;
    if (typeof textItem?.text === 'string' && textItem.text.trim()) {
      textParts.push(textItem.text.trim());
    } else if (typeof item.text === 'string' && item.text.trim()) {
      textParts.push(item.text.trim());
    }
  }
  const text = textParts.join('\n').trim();
  const mediaItems = itemList.filter(item => [2, 4].includes(Number(item.type)));
  if (!text && !mediaItems.length) return undefined;

  const contextToken = typeof msg.context_token === 'string' ? msg.context_token : undefined;
  const externalId = String(msg.msg_id ?? msg.client_id ?? msg.seq ?? randomUUID());
  return {
    channelId,
    externalId,
    senderId: fromUserId,
    senderName: typeof msg.from_user_name === 'string' ? msg.from_user_name : undefined,
    target: fromUserId,
    text: text || '请查看收到的附件。',
    mediaItems,
    contextToken,
  };
}

/** Shared Tencent WeChat iLink Bot API POST caller eliminating duplicate headers/envelopes. */
async function callIlinkApi<T extends { ret?: number; errcode?: number }>(params: {
  base: string;
  botToken: string;
  path: string;
  body: Record<string, unknown>;
  timeoutMs: number;
  shutdownSignal: AbortSignal;
  httpErrorLabel: string;
  bizErrorLabel?: string;
  checkResultCode?: boolean;
}): Promise<T> {
  const res = await fetch(`${params.base}${params.path}`, {
    method: 'POST',
    headers: buildWechatIlinkHeaders(params.botToken),
    signal: buildRequestSignal(params.timeoutMs, params.shutdownSignal),
    body: JSON.stringify({
      base_info: { channel_version: '1.0.2' },
      ...params.body,
    }),
  });
  if (!res.ok) {
    throw new Error(`${params.httpErrorLabel} HTTP ${res.status}`);
  }
  const data = await res.json() as T;
  if (params.checkResultCode !== false) {
    if ((data.ret !== undefined && data.ret !== 0) || (data.errcode !== undefined && data.errcode !== 0)) {
      throw new Error(params.bizErrorLabel ?? `${params.httpErrorLabel}业务错误`);
    }
  }
  return data;
}

/** Channel adapter for Tencent WeChat iLink QR-bound personal accounts. */
export class WechatIlinkAdapter implements ImChannelAdapter {
  readonly platform = 'wechat' as const;

  private readonly qrSessions = new BoundedMap<string, InternalWechatQrSession>(64);
  private readonly typingTickets = new BoundedMap<string, WechatTypingTicketEntry>(256);
  private readonly typingSessions = new Map<string, WechatTypingSession>();
  typingKeepaliveMs = WECHAT_TYPING_KEEPALIVE_MS;

  constructor(
    private readonly ctx: ImGatewayContext,
    private readonly host: WechatIlinkHostHooks,
  ) {}

  close(): void {
    for (const session of this.typingSessions.values()) {
      session.activeRefs.clear();
      if (session.timer) clearTimeout(session.timer);
      session.timer = undefined;
      session.remoteTyping = false;
    }
    this.typingSessions.clear();
    this.typingTickets.clear();
    this.qrSessions.clear();
  }

  attachmentDir(): string | undefined {
    if (process.env.FRIDAY_WECHAT_ATTACHMENT_DIR !== undefined) {
      return process.env.FRIDAY_WECHAT_ATTACHMENT_DIR.trim() || undefined;
    }
    return this.ctx.homeDir ? join(this.ctx.homeDir, 'wechat-files') : undefined;
  }

  isPeerAuthorized(channel: ImChannelConfig, senderId: string): boolean {
    if (channel.platform !== 'wechat' || !channel.enabled || !senderId) return false;
    return channel.allowedSenders.includes(senderId);
  }

  async send(channel: ImChannelConfig, text: string, options?: ImSendOptions): Promise<void> {
    if (!options?.target) {
      throw new Error('微信扫码通道尚未绑定对话目标（请先在手机微信向机器人发送一条消息以激活会话，或配置 defaultTarget）');
    }
    const base = (channel.apiBase ?? DEFAULT_WECHAT_ILINK_BASE).replace(/\/$/, '');
    const contextToken = options.contextToken
      ?? channel.contextTokens?.[options.target]
      ?? '';
    const { text: outText, stickers } = transformOutboundBotExpressions(text, 'wechat');
    const canSendStickers = Boolean(channel.botToken && contextToken);
    const effectiveText = (!canSendStickers && !outText.trim() && stickers.length > 0)
      ? stickers.map(expr => BOT_EXPRESSION_META[expr].wechatFallback).join(' ')
      : outText;

    if (effectiveText.trim().length > 0 || stickers.length === 0) {
      await callIlinkApi({
        base,
        botToken: channel.botToken ?? '',
        path: '/ilink/bot/sendmessage',
        timeoutMs: 30_000,
        shutdownSignal: this.ctx.shutdownSignal,
        httpErrorLabel: '微信 iLink 发送失败:',
        bizErrorLabel: '微信 iLink 业务发送失败',
        body: {
          msg: {
            from_user_id: channel.accountId ?? '',
            to_user_id: options.target,
            client_id: `friday-${randomUUID()}`,
            message_type: 2,
            message_state: 2,
            context_token: contextToken,
            item_list: [
              {
                type: 1,
                text_item: { text: effectiveText },
              },
            ],
          },
        },
      });
    }

    if (canSendStickers && stickers.length > 0) {
      const headers = buildWechatIlinkHeaders(channel.botToken!);
      for (const expr of stickers) {
        await deliverWechatImage({
          filePath: resolveBotStickerPath(expr),
          target: options.target,
          contextToken,
          contextTokenUpdatedAt: channel.contextTokenUpdatedAt?.[options.target] ?? channel.lastInboundAt,
          accountId: channel.accountId,
          base,
          headers,
          channelId: channel.id,
          signal: this.ctx.shutdownSignal,
        });
      }
    }
  }

  async poll(channel: ImChannelConfig): Promise<{ receivedAny: boolean }> {
    if (!channel.botToken) return { receivedAny: false };
    const base = (channel.apiBase ?? DEFAULT_WECHAT_ILINK_BASE).replace(/\/$/, '');
    const data = await callIlinkApi<{
      ret?: number;
      errcode?: number;
      get_updates_buf?: string;
      msgs?: Array<Record<string, unknown>>;
    }>({
      base,
      botToken: channel.botToken,
      path: '/ilink/bot/getupdates',
      timeoutMs: 40_000,
      shutdownSignal: this.ctx.shutdownSignal,
      httpErrorLabel: '微信 iLink getupdates',
      checkResultCode: false,
      body: {
        get_updates_buf: channel.syncBuf ?? '',
      },
    });

    let receivedAny = false;
    if (Array.isArray(data.msgs)) {
      receivedAny = data.msgs.length > 0;
      for (const msg of data.msgs) {
        const inbound = parseWechatIlinkMessage(channel.id, msg, channel.accountId);
        if (inbound) {
          this.ctx.markTrustedWechatInbound(inbound);
          await this.ctx.ingestMessage(inbound);
        }
      }
    }
    if (typeof data.get_updates_buf === 'string' && data.get_updates_buf !== channel.syncBuf) {
      const current = this.ctx.coordinator.store.getImChannel(channel.id);
      current.syncBuf = data.get_updates_buf;
      this.ctx.coordinator.store.saveImChannel(current);
    }
    return { receivedAny };
  }

  async sendAttachment(
    channelId: string,
    name: string,
    options: { target: string; contextToken?: string },
  ): Promise<void> {
    const channel = this.ctx.coordinator.store.getImChannel(channelId);
    const root = this.attachmentDir();
    const contextToken = options.contextToken ?? channel.contextTokens?.[options.target] ?? '';
    if (
      channel.platform !== 'wechat'
      || !channel.enabled
      || !channel.botToken
      || channel.webhookUrl
      || !root
      || !options.target
      || !contextToken
      || !this.isPeerAuthorized(channel, options.target)
    ) {
      throw new Error('微信附件发送未获授权或缺少会话凭证');
    }
    if (process.env.FRIDAY_WECHAT_ATTACHMENT_DIR === undefined) {
      await mkdir(root, { recursive: true, mode: 0o700 }).catch(() => {});
    }
    try {
      await deliverWechatFile({
        root,
        name: name.trim(),
        target: options.target,
        contextToken,
        contextTokenUpdatedAt: channel.contextTokenUpdatedAt?.[options.target] ?? channel.lastInboundAt,
        accountId: channel.accountId,
        base: (channel.apiBase ?? DEFAULT_WECHAT_ILINK_BASE).replace(/\/$/, ''),
        headers: buildWechatIlinkHeaders(channel.botToken),
        signal: this.ctx.shutdownSignal,
      });
      const latest = this.ctx.coordinator.store.getImChannel(channelId);
      latest.outboundCount++;
      latest.lastOutboundAt = Date.now();
      latest.lastError = undefined;
      latest.updatedAt = Date.now();
      this.ctx.coordinator.store.saveImChannel(latest);
    } catch (error) {
      const latest = this.ctx.coordinator.store.getImChannel(channelId);
      latest.lastError = error instanceof Error ? error.message : 'Attachment delivery failed; no automatic retry';
      latest.updatedAt = Date.now();
      this.ctx.coordinator.store.saveImChannel(latest);
      throw error;
    }
  }

  async handleSlashFileCommand(params: {
    channel: ImChannelConfig;
    inbound: ImInboundMessage;
    rawText: string;
    authorizedPeer: boolean;
    trustedFile: boolean;
    replyOpts: ImSendOptions;
  }): Promise<{ ok: boolean; action: string; reason?: string }> {
    const { channel, inbound, rawText, authorizedPeer, trustedFile, replyOpts } = params;
    const root = this.attachmentDir();
    if (
      !trustedFile
      || channel.platform !== 'wechat'
      || !channel.enabled
      || !channel.botToken
      || channel.webhookUrl
      || !root
      || !authorizedPeer
      || !inbound.contextToken
      || inbound.target !== inbound.senderId
    ) {
      return { ok: false, action: 'rejected', reason: 'attachment_not_authorized' };
    }
    if (process.env.FRIDAY_WECHAT_ATTACHMENT_DIR === undefined) {
      await mkdir(root, { recursive: true, mode: 0o700 }).catch(() => {});
    }
    try {
      await deliverWechatFile({
        root,
        name: rawText.slice(6).trim(),
        target: inbound.senderId,
        contextToken: inbound.contextToken,
        accountId: channel.accountId,
        base: (channel.apiBase ?? DEFAULT_WECHAT_ILINK_BASE).replace(/\/$/, ''),
        headers: buildWechatIlinkHeaders(channel.botToken),
        signal: this.ctx.shutdownSignal,
      });
      channel.outboundCount++;
      channel.lastOutboundAt = Date.now();
      channel.lastError = undefined;
      this.ctx.coordinator.store.saveImChannel(channel);
      return { ok: true, action: 'attachment_sent' };
    } catch (error) {
      channel.lastError = error instanceof Error ? error.message : 'Attachment delivery failed; no automatic retry';
      this.ctx.coordinator.store.saveImChannel(channel);
      await this.ctx.sendToChannel(
        channel.id,
        `⚠️ 附件发送失败（请确认文件已放入目录 ${root}）：${channel.lastError}`,
        replyOpts,
      ).catch(() => {});
      return { ok: false, action: 'attachment_failed', reason: 'delivery_failed' };
    }
  }

  async startQrLogin(input?: {
    id?: string;
    name?: string;
    apiBase?: string;
    notifyAll?: boolean;
    allowedSenders?: string[];
  }): Promise<WechatQrLoginSession> {
    this.pruneExpiredQrSessions();
    let existing: ImChannelConfig | undefined;
    if (input?.id) {
      try { existing = this.ctx.coordinator.store.getImChannel(input.id); } catch { /* create new */ }
    } else {
      existing = this.ctx.coordinator.store.listImChannels().find(ch => ch.platform === 'wechat');
    }

    const channelId = existing?.id ?? input?.id?.trim() ?? 'wechat-clawbot';
    const channelName = (input?.name?.trim() || existing?.name || '微信个人号 (扫码绑定)').slice(0, 120);
    const apiBase = (input?.apiBase?.trim() || existing?.apiBase || DEFAULT_WECHAT_ILINK_BASE).replace(/\/$/, '');

    const channelView = this.host.saveWechatChannel({
      id: channelId,
      platform: 'wechat',
      name: channelName,
      apiBase,
      notifyAll: input?.notifyAll ?? existing?.notifyAll ?? false,
      allowedSenders: input?.allowedSenders ?? existing?.allowedSenders,
    });

    const url = `${apiBase}/ilink/bot/get_bot_qrcode?bot_type=3`;
    const res = await fetch(url, {
      method: 'GET',
      headers: {
        Accept: 'application/json',
        'iLink-App-ClientVersion': '1',
      },
      signal: buildRequestSignal(10_000, this.ctx.shutdownSignal),
    });
    if (!res.ok) {
      throw new Error(`获取微信登录二维码失败: HTTP ${res.status}`);
    }
    const data = await res.json() as Record<string, unknown>;
    const qrcode = String(data.qrcode ?? '').trim();
    const qrcodeContent = String(data.qrcode_img_content ?? data.qrcode_url ?? qrcode).trim();
    if (!qrcode || !qrcodeContent) {
      throw new Error(`微信 iLink 返回的二维码数据不完整: ${JSON.stringify(data).slice(0, 200)}`);
    }

    const qrSvgDataUrl = qrcodeContent.startsWith('data:image/')
      ? qrcodeContent
      : renderQrSvgDataUrl(qrcodeContent);
    const qrTerminal = renderQrTerminal(qrcodeContent);
    const sessionId = randomUUID();

    const session: InternalWechatQrSession = {
      sessionId,
      channelId,
      channelName,
      qrcode,
      qrcodeContent,
      qrSvgDataUrl,
      qrTerminal,
      status: 'wait',
      apiBase,
      createdAt: Date.now(),
      channel: channelView,
    };
    this.qrSessions.set(sessionId, session);
    return this.toPublicQrSession(session);
  }

  async pollQrLogin(sessionIdOrChannelId: string): Promise<WechatQrLoginSession> {
    this.pruneExpiredQrSessions();
    let session = this.qrSessions.get(sessionIdOrChannelId);
    if (!session) {
      for (const candidate of this.qrSessions.values()) {
        if (candidate.channelId === sessionIdOrChannelId || candidate.qrcode === sessionIdOrChannelId) {
          session = candidate;
        }
      }
    }
    if (!session) {
      throw new Error('未找到进行中的微信扫码会话，请重新发起扫码绑定');
    }
    if (session.status === 'confirmed' || session.status === 'expired') {
      return this.toPublicQrSession(session);
    }

    if (!session.inFlightPromise) {
      session.inFlightPromise = this.fetchQrStatusOnce(session).finally(() => {
        session.inFlightPromise = undefined;
      });
    }

    await Promise.race([
      session.inFlightPromise,
      new Promise<void>((resolve) => {
        const timer = setTimeout(resolve, 400);
        timer.unref();
      }),
    ]);

    return this.toPublicQrSession(session);
  }

  private pruneExpiredQrSessions(): void {
    const cutoff = Date.now() - WECHAT_QR_SESSION_TTL_MS;
    for (const [id, session] of this.qrSessions.entries()) {
      if (session.createdAt < cutoff) {
        this.qrSessions.delete(id);
      }
    }
  }

  private async fetchQrStatusOnce(session: InternalWechatQrSession): Promise<void> {
    const url = `${session.apiBase}/ilink/bot/get_qrcode_status?qrcode=${encodeURIComponent(session.qrcode)}`;
    try {
      const res = await fetch(url, {
        method: 'GET',
        headers: {
          Accept: 'application/json',
          'iLink-App-ClientVersion': '1',
        },
        signal: buildRequestSignal(36_000, this.ctx.shutdownSignal),
      });
      if (!res.ok) {
        throw new Error(`轮询二维码状态失败: HTTP ${res.status}`);
      }
      const data = await res.json() as Record<string, unknown>;
      const rawStatus = String(data.status ?? 'wait').toLowerCase();
      session.error = undefined;
      if (rawStatus === 'scaned' || rawStatus === 'scanned') {
        session.status = 'scaned';
      } else if (rawStatus === 'confirmed') {
        const botToken = String(data.bot_token ?? '').trim();
        const accountId = String(data.ilink_bot_id ?? '').trim() || undefined;
        const userId = typeof data.ilink_user_id === 'string' && data.ilink_user_id.trim()
          ? data.ilink_user_id.trim()
          : undefined;
        const returnedBaseUrl = typeof data.baseurl === 'string' && data.baseurl.trim()
          ? data.baseurl.trim().replace(/\/$/, '')
          : session.apiBase;

        if (!botToken) {
          throw new Error('微信扫码已确认，但未返回 bot_token');
        }

        const channel = this.ctx.coordinator.store.getImChannel(session.channelId);
        channel.enabled = true;
        channel.botToken = botToken;
        channel.accountId = accountId ?? channel.accountId;
        channel.apiBase = returnedBaseUrl;
        if (userId) {
          if (!channel.defaultTarget) {
            channel.defaultTarget = userId;
          }
          if (!channel.allowedSenders.includes(userId)) {
            channel.allowedSenders = [...channel.allowedSenders, userId];
          }
        }
        channel.lastError = undefined;
        channel.updatedAt = Date.now();
        this.ctx.coordinator.store.saveImChannel(channel);
        this.host.syncPollers();

        session.status = 'confirmed';
        session.accountId = channel.accountId;
        session.userId = userId ?? channel.defaultTarget;
        session.channel = this.ctx.coordinator.store.toImChannelView(channel);
      } else if (rawStatus === 'expired' || rawStatus === 'canceled' || rawStatus === 'cancelled') {
        session.status = 'expired';
      } else {
        session.status = 'wait';
      }
    } catch (error) {
      if (error instanceof Error && (error.name === 'TimeoutError' || error.name === 'AbortError')) {
        return;
      }
      session.error = error instanceof Error ? error.message : 'Poll QR status error';
    }
  }

  private toPublicQrSession(session: InternalWechatQrSession): WechatQrLoginSession {
    let channel = session.channel;
    try {
      channel = this.ctx.coordinator.store.toImChannelView(
        this.ctx.coordinator.store.getImChannel(session.channelId),
      );
    } catch { /* ignore */ }
    return {
      sessionId: session.sessionId,
      channelId: session.channelId,
      channelName: session.channelName,
      qrcode: session.qrcode,
      qrcodeContent: session.qrcodeContent,
      qrSvgDataUrl: session.qrSvgDataUrl,
      qrTerminal: session.qrTerminal,
      status: session.status,
      accountId: session.accountId,
      userId: session.userId,
      error: session.error,
      channel,
    };
  }

  private typingSessionKey(channelId: string, userId: string): string {
    return `${channelId}\0${userId}`;
  }

  private canSendTyping(
    channel: ImChannelConfig | undefined,
    userId?: string,
    replyWebhook?: string,
  ): channel is ImChannelConfig {
    return Boolean(
      this.host.isRunning()
      && !this.ctx.isClosing()
      && channel
      && channel.enabled
      && channel.platform === 'wechat'
      && channel.botToken
      && !channel.webhookUrl
      && !replyWebhook
      && userId,
    );
  }

  clearChannelTyping(channelId: string): void {
    const prefix = `${channelId}\0`;
    for (const [key, session] of this.typingSessions.entries()) {
      if (key.startsWith(prefix)) {
        session.activeRefs.clear();
        if (session.timer) clearTimeout(session.timer);
        session.timer = undefined;
        session.remoteTyping = false;
        this.typingSessions.delete(key);
      }
    }
    for (const key of this.typingTickets.keys()) {
      if (key.startsWith(prefix)) this.typingTickets.delete(key);
    }
  }

  syncTypingForMissingMessage(messageId: string, releases: Array<{ channelId: string; target: string; ref: string }>): void {
    const ref = `msg:${messageId}`;
    for (const [key, session] of this.typingSessions.entries()) {
      if (session.activeRefs.has(ref)) {
        const [chId, target] = key.split('\0');
        if (chId && target) releases.push({ channelId: chId, target, ref });
      }
    }
  }

  syncTypingFromMessage(msg: ChatMessage, releases: Array<{ channelId: string; target: string; ref: string }>): void {
    if (msg.origin?.channel === 'wechat' && msg.origin.channelId && msg.origin.conversationId && !msg.origin.replyWebhook) {
      const active = (msg.role === 'user' && ['queued', 'processing'].includes(msg.status))
        || (msg.role === 'assistant' && msg.status === 'streaming');
      if (active) {
        this.retainTyping(msg.origin.channelId, msg.origin.conversationId, `msg:${msg.id}`, msg.origin.contextToken);
      } else if (['completed', 'failed', 'interrupted'].includes(msg.status)) {
        releases.push({
          channelId: msg.origin.channelId,
          target: msg.origin.conversationId,
          ref: `msg:${msg.id}`,
        });
      }
    }
  }

  retainTyping(
    channelId: string,
    userId: string,
    ref: string,
    contextToken?: string,
    replyWebhook?: string,
  ): void {
    let channel: ImChannelConfig;
    try {
      channel = this.ctx.coordinator.store.getImChannel(channelId);
    } catch {
      return;
    }
    if (!this.canSendTyping(channel, userId, replyWebhook)) return;

    const key = this.typingSessionKey(channelId, userId);
    let session = this.typingSessions.get(key);
    const wasIdle = !session || session.activeRefs.size === 0;
    if (!session) {
      session = {
        channelId,
        userId,
        contextToken,
        activeRefs: new Set(),
        chain: Promise.resolve(),
        remoteTyping: false,
      };
      this.typingSessions.set(key, session);
    } else if (contextToken) {
      session.contextToken = contextToken;
    }
    session.activeRefs.add(ref);
    if (wasIdle) {
      this.enqueueTypingPulse(key, session);
    }
  }

  releaseTyping(channelId: string, userId: string, ref: string): void {
    const key = this.typingSessionKey(channelId, userId);
    const session = this.typingSessions.get(key);
    if (!session) return;
    session.activeRefs.delete(ref);
    if (session.activeRefs.size > 0) return;
    if (session.timer) {
      clearTimeout(session.timer);
      session.timer = undefined;
    }
    session.chain = session.chain.then(async () => {
      if (session.activeRefs.size > 0) return;
      await this.stopTypingNow(key, session);
    }).catch(() => {});
  }

  private pruneSettledTypingRefs(session: WechatTypingSession): void {
    for (const ref of [...session.activeRefs]) {
      if (!ref.startsWith('msg:')) continue;
      try {
        const msg = this.ctx.coordinator.store.conversation.get(ref.slice(4));
        const active = (msg.role === 'user' && ['queued', 'processing'].includes(msg.status))
          || (msg.role === 'assistant' && msg.status === 'streaming');
        if (!active) session.activeRefs.delete(ref);
      } catch {
        session.activeRefs.delete(ref);
      }
    }
  }

  private enqueueTypingPulse(key: string, session: WechatTypingSession): void {
    if (session.timer) {
      clearTimeout(session.timer);
      session.timer = undefined;
    }
    session.chain = session.chain.then(async () => {
      this.pruneSettledTypingRefs(session);
      if (this.ctx.isClosing() || session.activeRefs.size === 0) {
        await this.stopTypingNow(key, session);
        return;
      }
      let channel: ImChannelConfig;
      try {
        channel = this.ctx.coordinator.store.getImChannel(session.channelId);
      } catch {
        this.clearChannelTyping(session.channelId);
        return;
      }
      if (!this.canSendTyping(channel, session.userId)) {
        session.activeRefs.clear();
        await this.stopTypingNow(key, session);
        return;
      }
      const ticketInfo = await this.getTypingTicket(channel, session.userId, session.contextToken);
      if (!ticketInfo) {
        this.scheduleNextTypingPulse(key, session);
        return;
      }
      this.pruneSettledTypingRefs(session);
      if (this.ctx.isClosing() || session.activeRefs.size === 0) {
        await this.stopTypingNow(key, session);
        return;
      }
      let ok = await this.postTypingStatus(channel, session.userId, ticketInfo.ticket, 1);
      if (!ok && ticketInfo.fromCache && !this.ctx.isClosing() && session.activeRefs.size > 0) {
        const refreshed = await this.getTypingTicket(channel, session.userId, session.contextToken);
        if (refreshed && !this.ctx.isClosing() && session.activeRefs.size > 0) {
          ok = await this.postTypingStatus(channel, session.userId, refreshed.ticket, 1);
        }
      }
      if (ok) session.remoteTyping = true;
      if (this.ctx.isClosing() || session.activeRefs.size === 0) {
        await this.stopTypingNow(key, session);
        return;
      }
      this.scheduleNextTypingPulse(key, session);
    }).catch(() => {});
  }

  private scheduleNextTypingPulse(key: string, session: WechatTypingSession): void {
    if (this.ctx.isClosing() || session.activeRefs.size === 0) return;
    if (session.timer) clearTimeout(session.timer);
    session.timer = setTimeout(() => {
      session.timer = undefined;
      this.enqueueTypingPulse(key, session);
    }, this.typingKeepaliveMs);
    session.timer.unref();
  }

  private async stopTypingNow(key: string, session: WechatTypingSession): Promise<void> {
    if (session.timer) {
      clearTimeout(session.timer);
      session.timer = undefined;
    }
    if (session.remoteTyping && !this.ctx.isClosing()) {
      session.remoteTyping = false;
      try {
        const channel = this.ctx.coordinator.store.getImChannel(session.channelId);
        if (channel.enabled && channel.platform === 'wechat' && channel.botToken && !channel.webhookUrl) {
          const cached = this.typingTickets.get(key);
          if (cached && cached.botToken === channel.botToken) {
            await this.postTypingStatus(channel, session.userId, cached.ticket, 2);
          }
        }
      } catch { /* best-effort */ }
    }
    if (session.activeRefs.size === 0 && this.typingSessions.get(key) === session) {
      this.typingSessions.delete(key);
    }
  }

  private async getTypingTicket(
    channel: ImChannelConfig,
    userId: string,
    contextToken?: string,
  ): Promise<{ ticket: string; fromCache: boolean } | undefined> {
    if (!channel.botToken) return undefined;
    const key = this.typingSessionKey(channel.id, userId);
    const cached = this.typingTickets.get(key);
    if (cached && cached.botToken === channel.botToken && Date.now() < cached.expiresAt) {
      return { ticket: cached.ticket, fromCache: true };
    }
    try {
      const base = (channel.apiBase ?? DEFAULT_WECHAT_ILINK_BASE).replace(/\/$/, '');
      const resolvedContextToken = contextToken ?? channel.contextTokens?.[userId] ?? '';
      const data = await callIlinkApi<{ ret?: number; errcode?: number; typing_ticket?: string }>({
        base,
        botToken: channel.botToken,
        path: '/ilink/bot/getconfig',
        timeoutMs: 10_000,
        shutdownSignal: this.ctx.shutdownSignal,
        httpErrorLabel: '微信 getconfig',
        body: {
          ilink_user_id: userId,
          ...(resolvedContextToken ? { context_token: resolvedContextToken } : {}),
        },
      });
      const ticket = typeof data.typing_ticket === 'string' ? data.typing_ticket.trim() : '';
      if (!ticket) return undefined;
      this.typingTickets.set(key, {
        ticket,
        botToken: channel.botToken,
        expiresAt: Date.now() + WECHAT_TYPING_TICKET_TTL_MS,
      });
      return { ticket, fromCache: false };
    } catch {
      return undefined;
    }
  }

  private async postTypingStatus(
    channel: ImChannelConfig,
    userId: string,
    ticket: string,
    status: 1 | 2,
  ): Promise<boolean> {
    if (!channel.botToken) return false;
    const key = this.typingSessionKey(channel.id, userId);
    try {
      const base = (channel.apiBase ?? DEFAULT_WECHAT_ILINK_BASE).replace(/\/$/, '');
      await callIlinkApi({
        base,
        botToken: channel.botToken,
        path: '/ilink/bot/sendtyping',
        timeoutMs: 10_000,
        shutdownSignal: this.ctx.shutdownSignal,
        httpErrorLabel: '微信 sendtyping',
        body: {
          ilink_user_id: userId,
          typing_ticket: ticket,
          status,
        },
      });
      return true;
    } catch {
      this.typingTickets.delete(key);
      return false;
    }
  }
}
